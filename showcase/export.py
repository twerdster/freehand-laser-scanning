"""Export bounded observations and all computed scan points, not the scene mesh."""
import argparse
import json
from pathlib import Path
import shutil
import numpy as np
from .generate import ROOT, sha, write_json, write_ply


def export(cache, output):
    output.mkdir(parents=True, exist_ok=True)
    selected = [p*60+h for p in range(6) for h in (12, 24, 36, 48)]
    files = ['configuration.json', 'calibration.json', 'metrics.json', 'reconstruction.npz', 'reconstruction.ply']
    files += [f'captures/{i:04}.png' for i in selected]
    files += [f'calibration/{i:03}.png' for i in range(8)]
    for name in files:
        target = output/name
        target.parent.mkdir(parents=True, exist_ok=True)
        shutil.copyfile(cache/name, target)
    data = np.load(cache/'reconstruction.npz', allow_pickle=False)
    # A deterministic display subset; the NPZ keeps every accepted point.
    stride = 3
    write_ply(output/'preview.ply', data['xyz'][::stride], data['view_index'][::stride])
    files.append('preview.ply')
    report = {
        'schema': 1, 'scope': 'All computed XYZ/UV/view IDs and poses, plus selected source PNGs',
        'all_views': len(data['camera_to_world']), 'all_points': len(data['xyz']),
        'selected_capture_indices': selected, 'calibration_frames': 8,
        'preview_stride': stride, 'preview_points': len(data['xyz'][::stride]),
        'full_capture_cache': '360 PNGs regenerated by showcase.generate; their hashes/poses are in metrics.json',
        'license': 'Stanford research-use asset terms; software separately MIT',
        'files': {name: {'sha256': sha(output/name), 'bytes': (output/name).stat().st_size} for name in files},
    }
    write_json(output/'manifest.json', report)
    return report


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--cache', type=Path, required=True)
    parser.add_argument('--output', type=Path, default=ROOT/'data')
    args = parser.parse_args()
    print(json.dumps(export(args.cache, args.output), indent=2))

if __name__ == '__main__': main()
